def mask(*paths, blur=0):
    result = Image.new("L", SIZE)
    draw = ImageDraw.Draw(result)
    for path in paths:
        points = [tuple(map(float, point.split(","))) for point in path.split()]
        draw.polygon([(round(x * SIZE[0] / REFERENCE_SIZE[0]),
                       round(y * SIZE[1] / REFERENCE_SIZE[1])) for x, y in points], fill=255)
    return result.filter(ImageFilter.GaussianBlur(blur)) if blur else result


def union(*masks):
    result = Image.new("L", SIZE)
    for layer in masks:
        result = ImageChops.lighter(result, layer)
    return result


def load(path):
    with Image.open(path) as image:
        return image.convert("RGB").resize(SIZE, Image.Resampling.LANCZOS)


def restore(original, plate, removed):
    # Preserve original pixels away from the inpainted area.
    small = removed.resize((638, 360), Image.Resampling.BOX)
    blend = small.filter(ImageFilter.MaxFilter(15)).filter(ImageFilter.GaussianBlur(2))
    blend = blend.resize(SIZE, Image.Resampling.BILINEAR)
    return Image.composite(plate, original, blend)


def write(folder, name, image, alpha):
    path = OUT / folder / f"{name}.png"
    path.parent.mkdir(parents=True, exist_ok=True)
    sprite = image.convert("RGBA")
    sprite.putalpha(alpha)
    sprite.save(path, dpi=(72, 72))
    return path


def panel(folder, original, plate, bounds, layers, *, use_full_plate=False):
    clipped = [(name, ImageChops.multiply(shape, bounds)) for name, shape in layers]
    background = plate if use_full_plate else restore(original, plate, union(*(shape for _, shape in clipped)))
    write(folder, "01_background", background, bounds)
    for name, shape in clipped:
        write(folder, name, original, shape)


