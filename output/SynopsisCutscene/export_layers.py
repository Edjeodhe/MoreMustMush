def main():
    plates = [load(Path(path)) for path in sys.argv[1:]]
    if len(plates) != 5:
        raise ValueError("Pass four clean plates and one dusty page-one plate.")
    originals = [
        load(Path.home() / "AppData/Local/Temp" / f"codex-clipboard-{attachment}.png")
        for attachment in ATTACHMENTS
    ]
    OUT.mkdir(exist_ok=True)

    p1, p2, p3, p4 = originals
    actors = union(P1_KING, P1_PEOPLE)
    clean = restore(p1, plates[0], union(actors, P1_DUST))
    dusty = restore(p1, plates[4], actors)
    dust_area = P1_DUST.resize((638, 360), Image.Resampling.BOX)
    dust_area = dust_area.filter(ImageFilter.MaxFilter(15)).filter(ImageFilter.GaussianBlur(2))
    dusty = Image.composite(dusty, clean, dust_area.resize(SIZE, Image.Resampling.BILINEAR))
    write("page_01", "01_background_clean", clean, FULL)
    write("page_01", "02_background_with_dust", dusty, FULL)
    write("page_01", "03_landing_king", p1, P1_KING)
    write("page_01", "04_fleeing_people", p1, P1_PEOPLE)

    panel("page_02/panel_01", p2, plates[1], P2_TL, [
        ("02_grandfather_harvesting", P2_HARVEST),
        ("03_fleeing_people", P2_RUNNERS),
    ])
    panel("page_02/panel_02", p2, plates[1], P2_BL, [
        ("02_grandfather_turning", P2_TURN),
    ])
    panel("page_02/panel_03", p2, plates[1], P2_R, [
        ("02_giant_mushrooms", ImageChops.subtract(P2_GIANTS, union(P2_PLANTS, P2_GRANDPA))),
        ("03_grandfather", P2_GRANDPA),
        ("04_foreground_plants", P2_PLANTS),
    ])
    panel("page_03/panel_01", p3, plates[2], P3_TL, [
        ("02_grandfather_turning", P3_TURN),
    ], use_full_plate=True)
    panel("page_03/panel_02", p3, plates[2], P3_BL, [
        ("02_grandfather_bowing", P3_BOW),
        ("03_tremble_effect", P3_SHAKE),
    ], use_full_plate=True)
    panel("page_03/panel_03", p3, plates[2], P3_R, [
        ("02_heart_effect", ImageChops.subtract(P3_HEARTS, P3_JOY)),
        ("03_grandfather_with_mushroom", P3_JOY),
    ], use_full_plate=True)
    panel("page_04", p4, plates[3], FULL, [
        ("02_fleeing_mushrooms", P4_MUSHROOMS),
        ("03_grandfather_with_scythe", ImageChops.subtract(P4_GRANDPA, P4_BALLOON)),
        ("04_speech_balloon_and_hearts", P4_BALLOON),
    ])

    assets = sorted(OUT.rglob("*.png"))
    assert len(assets) == 25
    for path in assets:
        with Image.open(path) as image:
            assert image.size == SIZE and image.mode == "RGBA", path
            assert all(abs(value - 72) < .02 for value in image.info["dpi"]), path
            if "panel_" in path.parent.name or "background" not in path.name:
                assert image.getchannel("A").getextrema() == (0, 255), path

    archive = ROOT / "MoreMustMush_Synopsis_Layers.zip"
    with ZipFile(archive, "x", ZIP_STORED) as output:
        for path in assets:
            output.write(path, path.relative_to(OUT))
    with ZipFile(archive) as output:
        assert len(output.namelist()) == 25 and output.testzip() is None
    print(f"Verified {len(assets)} RGBA layers and {archive.name}.")


if __name__ == "__main__":
    main()
